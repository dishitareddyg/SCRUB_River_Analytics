"""
mission/validator.py

Validates the mission payload POSTed by the frontend (this is the
application API contract, NOT the STM32 UART packet):

{
  "mission_id": "UUID",
  "device_id": "BOT001",
  "lake_id": "UUID | null",            (optional)
  "ground_control": {"latitude": .., "longitude": ..},
  "polygon":   [{"latitude": .., "longitude": ..}, ...],
  "waypoints": [{"sequence_order": 0, "latitude": .., "longitude": .., "type": "GCS"},
                {"sequence_order": 1, ..., "type": "COVERAGE"}, ...,
                {"sequence_order": N, ..., "type": "GCS"}],
  "sweep_spacing_m": 5.0,              (optional, informational)
  "notes": "..."                       (optional)
}

The route is generated by the frontend; the RPi validates and executes
it verbatim and never generates a competing route.
"""

from __future__ import annotations

import hashlib
import json
import math
import uuid
from dataclasses import dataclass
from typing import Any, Optional

from config.settings import settings
from navigation.geometry import (
    distance_to_polygon_edge_m,
    is_self_intersecting,
    point_in_polygon,
    signed_area_m2,
    strip_closing_vertex,
    to_local,
)
from navigation.steering import haversine_distance

WAYPOINT_TYPES = ("GCS", "COVERAGE", "TRANSIT")


class MissionValidationError(ValueError):
    def __init__(self, errors: list[str]):
        super().__init__("; ".join(errors))
        self.errors = errors


@dataclass
class ValidatedMission:
    mission_id: str
    device_id: str
    lake_id: Optional[str]
    gcs: tuple[float, float]
    polygon: list[dict]        # [{"latitude", "longitude"}], open ring
    waypoints: list[dict]      # [{"sequence_order", "latitude", "longitude", "type"}]
    payload: dict              # normalised payload persisted to waypoints.json
    payload_hash: str
    notes: Optional[str] = None


def _coord(obj: Any, where: str, errors: list[str]) -> Optional[tuple[float, float]]:
    if not isinstance(obj, dict):
        errors.append(f"{where}: must be an object with latitude/longitude")
        return None
    lat, lon = obj.get("latitude"), obj.get("longitude")
    ok = True
    for name, val, lo, hi in (("latitude", lat, -90, 90), ("longitude", lon, -180, 180)):
        if isinstance(val, bool) or not isinstance(val, (int, float)) or not math.isfinite(val):
            errors.append(f"{where}.{name}: must be a finite number")
            ok = False
        elif not lo <= val <= hi:
            errors.append(f"{where}.{name}: {val} out of range [{lo}, {hi}]")
            ok = False
    if ok and lat == 0 and lon == 0:
        errors.append(f"{where}: (0, 0) is not a valid position")
        ok = False
    return (float(lat), float(lon)) if ok else None


def _uuid(value: Any, where: str, errors: list[str], required: bool = True) -> Optional[str]:
    if value is None and not required:
        return None
    try:
        return str(uuid.UUID(str(value)))
    except (ValueError, TypeError, AttributeError):
        errors.append(f"{where}: must be a UUID")
        return None


def payload_hash(payload: dict) -> str:
    return hashlib.sha256(json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def validate_mission_payload(raw: Any) -> ValidatedMission:
    errors: list[str] = []
    if not isinstance(raw, dict):
        raise MissionValidationError(["payload must be a JSON object"])

    mission_id = _uuid(raw.get("mission_id"), "mission_id", errors)
    lake_id = _uuid(raw.get("lake_id"), "lake_id", errors, required=False)

    device_id = raw.get("device_id")
    if not isinstance(device_id, str) or not device_id:
        errors.append("device_id: required")
    elif device_id != settings.DEVICE_ID:
        errors.append(f"device_id: {device_id!r} does not match this bot ({settings.DEVICE_ID!r})")

    gcs = _coord(raw.get("ground_control"), "ground_control", errors)

    # ---- polygon --------------------------------------------------------
    poly_raw = raw.get("polygon")
    polygon: list[tuple[float, float]] = []
    polygon_parsed = isinstance(poly_raw, list)
    if not polygon_parsed:
        errors.append("polygon: must be a list of coordinates")
    else:
        for i, p in enumerate(poly_raw):
            c = _coord(p, f"polygon[{i}]", errors)
            if c:
                polygon.append(c)
            else:
                polygon_parsed = False
        polygon = strip_closing_vertex(polygon)
        if len(poly_raw) > settings.MAX_POLYGON_VERTICES:
            errors.append(f"polygon: more than {settings.MAX_POLYGON_VERTICES} vertices")
    poly_xy = None
    if len(set(polygon)) < 3:
        errors.append("polygon: needs at least 3 distinct vertices")
    elif polygon_parsed:
        poly_xy = to_local(polygon, polygon[0])
        if is_self_intersecting(poly_xy):
            errors.append("polygon: edges self-intersect")
            poly_xy = None
        elif abs(signed_area_m2(poly_xy)) < 1.0:
            errors.append("polygon: area is zero / degenerate")
            poly_xy = None

    # ---- waypoints ------------------------------------------------------
    wps_raw = raw.get("waypoints")
    waypoints: list[dict] = []
    if not isinstance(wps_raw, list) or not wps_raw:
        errors.append("waypoints: must be a non-empty list")
        wps_raw = []
    if len(wps_raw) > settings.MAX_MISSION_WAYPOINTS:
        errors.append(f"waypoints: more than {settings.MAX_MISSION_WAYPOINTS} waypoints")
    if wps_raw and len(wps_raw) < 3:
        errors.append("waypoints: need at least GCS, one traversal waypoint and GCS return")

    seen: set[int] = set()
    for i, w in enumerate(wps_raw):
        where = f"waypoints[{i}]"
        if not isinstance(w, dict):
            errors.append(f"{where}: must be an object")
            continue
        seq = w.get("sequence_order")
        if isinstance(seq, bool) or not isinstance(seq, int):
            errors.append(f"{where}.sequence_order: must be an integer")
            continue
        if seq in seen:
            errors.append(f"{where}.sequence_order: duplicate {seq}")
        seen.add(seq)
        wtype = w.get("type")
        if wtype not in WAYPOINT_TYPES:
            errors.append(f"{where}.type: must be one of {WAYPOINT_TYPES}")
        c = _coord(w, where, errors)
        if c:
            waypoints.append({"sequence_order": seq, "latitude": c[0], "longitude": c[1], "type": wtype})

    if wps_raw and seen and len(seen) == len(wps_raw):
        if [w.get("sequence_order") for w in wps_raw if isinstance(w, dict)] != list(range(len(wps_raw))):
            errors.append("waypoints: sequence_order must be 0..N-1 in ascending order without gaps")

    if waypoints and gcs and len(waypoints) == len(wps_raw):
        first, last = waypoints[0], waypoints[-1]
        for label, wp in (("first", first), ("final", last)):
            if wp["type"] != "GCS":
                errors.append(f"waypoints: {label} waypoint must be type GCS")
            elif haversine_distance(wp["latitude"], wp["longitude"], *gcs) > settings.GCS_MATCH_TOLERANCE_M:
                errors.append(f"waypoints: {label} waypoint does not match ground_control")
        for wp in waypoints[1:-1]:
            if wp["type"] == "GCS":
                errors.append(f"waypoints[{wp['sequence_order']}]: GCS type only allowed first/last")
        if not any(w["type"] == "COVERAGE" for w in waypoints):
            errors.append("waypoints: no COVERAGE waypoints")
        if poly_xy is not None:
            pts_xy = to_local([(w["latitude"], w["longitude"]) for w in waypoints], polygon[0])
            for wp, xy in zip(waypoints, pts_xy):
                if wp["type"] != "COVERAGE":
                    continue
                if not point_in_polygon(xy, poly_xy) and \
                        distance_to_polygon_edge_m(xy, poly_xy) > settings.POLYGON_TOLERANCE_M:
                    errors.append(f"waypoints[{wp['sequence_order']}]: COVERAGE point outside polygon")

    notes = raw.get("notes")
    if notes is not None and not isinstance(notes, str):
        errors.append("notes: must be a string")

    if errors:
        raise MissionValidationError(errors[:50])

    normalised = {
        "mission_id": mission_id,
        "device_id": device_id,
        "lake_id": lake_id,
        "ground_control": {"latitude": gcs[0], "longitude": gcs[1]},
        "polygon": [{"latitude": la, "longitude": lo} for la, lo in polygon],
        "waypoints": waypoints,
    }
    if isinstance(raw.get("sweep_spacing_m"), (int, float)) and not isinstance(raw.get("sweep_spacing_m"), bool):
        normalised["sweep_spacing_m"] = float(raw["sweep_spacing_m"])
    if notes:
        normalised["notes"] = notes

    return ValidatedMission(
        mission_id=mission_id,
        device_id=device_id,
        lake_id=lake_id,
        gcs=gcs,
        polygon=normalised["polygon"],
        waypoints=waypoints,
        payload=normalised,
        payload_hash=payload_hash(normalised),
        notes=notes,
    )
